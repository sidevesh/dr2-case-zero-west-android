#!/usr/bin/env bash
# gen-fsr-shaders.sh — for maintainers: compile native/fsr/dr2_fsr.comp (AMD FidelityFX
# FSR 1.0, MIT) to SPIR-V and write native/fsr/dr2_fsr_spv.h, which the runtime build
# embeds. The generated header is committed, so a normal build needs no GLSL compiler.
# Needs glslangValidator and spirv-val (Debian/Ubuntu: glslang-tools, spirv-tools).
source "$(dirname "$0")/common.sh"
need glslangValidator; need spirv-val; need python3
d="$DR2_DIR/native/fsr" tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for pass in EASU RCAS; do
    glslangValidator -V --target-env vulkan1.1 -DFSR_PASS_$pass=1 -I"$d" \
        -o "$tmp/$pass.spv" "$d/dr2_fsr.comp" >/dev/null || die "compiling $pass failed"
    spirv-val --target-env vulkan1.1 "$tmp/$pass.spv" || die "$pass SPIR-V does not validate"
done
python3 - "$tmp" "$d/dr2_fsr_spv.h" <<'PY'
import struct, sys
tmp, out = sys.argv[1], sys.argv[2]
with open(out, "w") as f:
    f.write("// GENERATED by scripts/gen-fsr-shaders.sh from native/fsr/dr2_fsr.comp — do not edit.\n")
    f.write("// AMD FidelityFX Super Resolution 1.0 (MIT; native/fsr/LICENSE-FidelityFX-FSR.txt).\n")
    f.write("#pragma once\n#include <cstdint>\n")
    for p in ("EASU", "RCAS"):
        data = open(f"{tmp}/{p}.spv", "rb").read()
        words = struct.unpack(f"<{len(data)//4}I", data)
        f.write(f"static const uint32_t kDr2Fsr{p.title()}Spv[{len(words)}] = {{\n")
        for i in range(0, len(words), 8):
            f.write("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i+8]) + ",\n")
        f.write("};\n")
PY
log "wrote $d/dr2_fsr_spv.h"
