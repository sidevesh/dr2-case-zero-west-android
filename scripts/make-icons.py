#!/usr/bin/env python3
"""make-icons.py <casezero|casewest> <game folder> <out res folder>

Makes the app's launcher icon from YOUR copy of the game: the box art every XBLA
package carries (X_IMAGEID_GAME_BOXART.PNG, 584x800). No game artwork is stored in
this repository; like the rest of the APK, the icon is built from the player's own
files (scripts/build-apk.sh calls this when the unpacked game is available, and the
APK falls back to the generic icon in android/app/src/main/res otherwise).

Writes an Android adaptive icon (API 26+): a background layer (the game's scene,
darkened) and a foreground layer (the game's logo, edges faded) at every density,
plus mipmap-anydpi-v26/ic_launcher.xml pointing at them. Layers are 108 dp; launchers
mask them to a circle or squircle around the central 66 dp "safe zone", so the logo
is sized to that.

Needs Python 3 with Pillow (Debian/Ubuntu: python3-pil).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter

# Box-art regions, in the 584x800 image's pixels: (left, top, right, bottom).
#   scene   the square the background is cut from
#   logo    the title logo, laid over it
#   logo_y  where the logo's centre sits, as a fraction of the icon's height
GAMES = {
    # The zombie crowd at the top of the cover; the neon logo with its blood-red
    # "CASE 0" stamp below it.
    "casezero": dict(scene=(200, 0, 480, 280), logo=(28, 300, 556, 556), logo_y=0.60,
                     logo_w=0.62, darken=0.95),
    # Chuck and Frank on the cliff at dusk; the logo with its "CASE WEST" band from
    # the bottom of the cover.
    "casewest": dict(scene=(30, 140, 450, 560), logo=(100, 630, 492, 790), logo_y=0.69,
                     logo_w=0.62, darken=0.95),
}

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
LAYER_DP = 108
MASTER = 432  # the xxxhdpi layer, drawn once and scaled down


def faded(img, feather):
    """`img` with its edges faded to transparent over `feather` pixels."""
    w, h = img.size
    mask = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(mask)
    steps = max(1, feather)
    for i in range(steps):
        v = int(255 * (i + 1) / steps)
        d.rectangle([i, i, w - 1 - i, h - 1 - i], outline=v)
    d.rectangle([steps, steps, w - 1 - steps, h - 1 - steps], fill=255)
    out = img.convert("RGBA")
    out.putalpha(mask)
    return out


def layers(game, art):
    g = GAMES[game]
    box = Image.open(art).convert("RGB")
    if box.size != (584, 800):
        box = box.resize((584, 800), Image.LANCZOS)

    bg = box.crop(g["scene"]).resize((MASTER, MASTER), Image.LANCZOS)
    bg = bg.filter(ImageFilter.GaussianBlur(1.2))
    bg = ImageEnhance.Brightness(bg).enhance(g["darken"])
    # A vignette, so the logo reads against any part of the scene.
    vig = Image.new("L", (MASTER, MASTER), 0)
    ImageDraw.Draw(vig).ellipse([-MASTER * 0.2, -MASTER * 0.2, MASTER * 1.2, MASTER * 1.2], fill=255)
    vig = vig.filter(ImageFilter.GaussianBlur(MASTER * 0.12))
    bg = Image.composite(bg, Image.new("RGB", bg.size, (0, 0, 0)), vig)

    logo = box.crop(g["logo"])
    lw = int(MASTER * g["logo_w"])
    lh = int(logo.height * lw / logo.width)
    logo = logo.resize((lw, lh), Image.LANCZOS)
    logo = ImageEnhance.Contrast(logo).enhance(1.15)
    logo = faded(logo, max(6, lh // 7))
    fg = Image.new("RGBA", (MASTER, MASTER), (0, 0, 0, 0))
    fg.alpha_composite(logo, ((MASTER - lw) // 2, int(MASTER * g["logo_y"] - lh / 2)))
    return bg, fg


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in GAMES:
        sys.exit(__doc__)
    game, folder, out = sys.argv[1:]
    art = None
    for name in os.listdir(folder):
        if name.lower() == "x_imageid_game_boxart.png":
            art = os.path.join(folder, name)
    if not art:
        sys.exit(f"no X_IMAGEID_GAME_BOXART.PNG in {folder}")
    bg, fg = layers(game, art)
    for dens, scale in DENSITIES.items():
        px = int(LAYER_DP * scale)
        d = os.path.join(out, f"mipmap-{dens}")
        os.makedirs(d, exist_ok=True)
        bg.resize((px, px), Image.LANCZOS).save(os.path.join(d, "ic_game_background.png"))
        fg.resize((px, px), Image.LANCZOS).save(os.path.join(d, "ic_game_foreground.png"))
    d = os.path.join(out, "mipmap-anydpi-v26")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "ic_launcher.xml"), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by scripts/make-icons.py from the player\'s own game files. -->\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@mipmap/ic_game_background" />\n'
                '    <foreground android:drawable="@mipmap/ic_game_foreground" />\n'
                '</adaptive-icon>\n')
    print(f"icon for {game} -> {out}")


if __name__ == "__main__":
    main()
